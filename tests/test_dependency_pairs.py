"""Dependencies that only work in pairs, read from the two lock files (neither cargo nor npm is needed).

"tauri build" refuses to build when an npm package of Tauri and its crate are not on the same major and minor
version: @tauri-apps/api with tauri, @tauri-apps/plugin-<name> with tauri-plugin-<name>. None of the other checks
runs "tauri build", so an update of one side alone would pass them all and stop the release workflow after its
tag has been pushed. Here it stops the pull request, which is where the other side is raised: see "Updating
dependencies" in CONTRIBUTING.md."""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def crate_versions(cargo_lock):
    """{crate: [versions]} of a Cargo.lock. Python 3.8 has no tomllib, and none is needed: cargo writes the file,
    and every [[package]] of it begins with its name and its version."""
    found = {}
    for name, version in re.findall(r'^\[\[package\]\]\r?\nname = "([^"]+)"\r?\nversion = "([^"]+)"', cargo_lock,
                                    re.M):
        found.setdefault(name, []).append(version)
    return found


def tauri_npm_packages(package_lock):
    """{npm package: version} of the packages "tauri build" compares with a crate: @tauri-apps/api and every
    @tauri-apps/plugin-*, as package-lock.json installs them at the top of node_modules. (@tauri-apps/cli is the
    build tool and has no partner.)"""
    packages = json.loads(package_lock)["packages"]
    return {key[len("node_modules/"):]: entry["version"] for key, entry in packages.items()
            if re.match(r"node_modules/@tauri-apps/(api|plugin-[^/]+)$", key)}


def crate_of(npm_package):
    name = npm_package.split("/", 1)[1]
    return "tauri" if name == "api" else "tauri-" + name


def out_of_step(cargo_lock, package_lock):
    """A sentence for every Tauri pair that "tauri build" would refuse; [] when all of them are in step. A patch
    release of one side alone is fine."""
    def major_minor(version):
        return version.split(".")[:2]

    crates = crate_versions(cargo_lock)
    found = []
    for package, version in sorted(tauri_npm_packages(package_lock).items()):
        crate = crate_of(package)
        if crate not in crates:
            # the page would call a plugin that the program does not hold
            found.append("%s %s (package-lock.json) has no crate %s in src-tauri/Cargo.lock"
                         % (package, version, crate))
        found += ["%s %s (package-lock.json) and %s %s (src-tauri/Cargo.lock) are not on the same major.minor"
                  % (package, version, crate, other)
                  for other in crates.get(crate, []) if major_minor(other) != major_minor(version)]
    return found


# ---------------------------------------------------------------- made-up lock files
def cargo_lock(**crates):
    packages = ['[[package]]\nname = "%s"\nversion = "%s"\nsource = "registry+https://example.org/index"\n'
                % (name.replace("_", "-"), version) for name, version in sorted(crates.items())]
    return "# This file is automatically @generated by Cargo.\nversion = 4\n\n" + "\n".join(packages)


def package_lock(**packages):
    entries = {"": {"name": "my-app", "version": "1.0.0"}}
    entries.update({"node_modules/" + name: {"version": version} for name, version in packages.items()})
    return json.dumps({"name": "my-app", "lockfileVersion": 3, "packages": entries})


API, DIALOG = "@tauri-apps/api", "@tauri-apps/plugin-dialog"


def test_pairs_on_the_same_minor_version_are_in_step_whatever_their_patch_level():
    crates = cargo_lock(tauri="2.12.1", tauri_plugin_dialog="2.8.0", tauri_build="2.7.1", serde="1.0.0")
    assert out_of_step(crates, package_lock(**{API: "2.12.4", DIALOG: "2.8.3", "react": "19.1.0"})) == []


def test_a_crate_that_was_raised_alone_is_named_with_its_partner():
    crates = cargo_lock(tauri="2.13.0", tauri_plugin_dialog="2.8.1")
    assert out_of_step(crates, package_lock(**{API: "2.12.1", DIALOG: "2.8.1"})) == [
        "@tauri-apps/api 2.12.1 (package-lock.json) and tauri 2.13.0 (src-tauri/Cargo.lock) are not on the same "
        "major.minor"]


def test_an_npm_package_that_was_raised_alone_is_named_with_its_partner():
    crates = cargo_lock(tauri="2.12.1", tauri_plugin_dialog="2.8.1")
    assert out_of_step(crates, package_lock(**{API: "3.0.0", DIALOG: "2.9.0"})) == [
        "@tauri-apps/api 3.0.0 (package-lock.json) and tauri 2.12.1 (src-tauri/Cargo.lock) are not on the same "
        "major.minor",
        "@tauri-apps/plugin-dialog 2.9.0 (package-lock.json) and tauri-plugin-dialog 2.8.1 (src-tauri/Cargo.lock) "
        "are not on the same major.minor"]


def test_a_plugin_of_the_page_without_its_crate_is_named():
    assert out_of_step(cargo_lock(tauri="2.12.1"), package_lock(**{API: "2.12.1", DIALOG: "2.8.1"})) == [
        "@tauri-apps/plugin-dialog 2.8.1 (package-lock.json) has no crate tauri-plugin-dialog in src-tauri/Cargo.lock"]


def test_only_the_packages_that_have_a_crate_are_compared():
    # the build tool, and a copy that some other package keeps for itself
    others = {"@tauri-apps/cli": "2.14.0", "@tauri-apps/cli-win32-x64-msvc": "2.14.0",
              "some-package/node_modules/@tauri-apps/api": "1.6.0", API: "2.12.1"}
    assert tauri_npm_packages(package_lock(**others)) == {API: "2.12.1"}
    assert out_of_step(cargo_lock(tauri="2.12.1"), package_lock(**others)) == []


# ---------------------------------------------------------------- the lock files of this repository
def test_the_tauri_packages_and_their_crates_are_in_step():
    with open(os.path.join(ROOT, "src-tauri", "Cargo.lock"), encoding="utf-8") as f:
        crates = f.read()
    with open(os.path.join(ROOT, "package-lock.json"), encoding="utf-8") as f:
        packages = f.read()
    # both files were read as what they are: a lock file in another form must not pass for want of pairs
    assert "tauri" in crate_versions(crates) and API in tauri_npm_packages(packages)
    assert out_of_step(crates, packages) == [], \
        "raise the other side of each pair in the same pull request (CONTRIBUTING.md, \"Updating dependencies\")"
